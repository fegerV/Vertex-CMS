    if (in_array($slug, $excludedReferenceSlugs, true)) {
        continue;
    }

    $parts = explode('\\', $slug);
    $shortName = (string) end($parts);
    $type = 'breakdance-' . $toKebab($shortName);
    $label = $humanize($shortName);
    $category = $resolveCategory($shortName);

    $referenceBlocks[$type] = [
        'name' => $label,
        'category' => $category,
        'icon' => 'reference',
        'description' => 'Breakdance reference block mapped from local source slug ' . $slug . '.',
