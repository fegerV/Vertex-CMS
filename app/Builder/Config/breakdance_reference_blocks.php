$toKebab = static function (string $value): string {
    $value = str_replace('\\', '-', $value);
    $value = preg_replace('/(?<=\p{Ll}|\p{Nd})(\p{Lu})/u', '-$1', $value) ?? $value;
    $value = preg_replace('/(?<=\p{Lu})(\p{Lu})(?=\p{Ll})/u', '-$1', $value) ?? $value;
    $value = preg_replace('/[^A-Za-z0-9]+/', '-', $value) ?? $value;

    return trim(strtolower($value), '-');
};

$humanize = static function (string $value): string {
    $value = preg_replace('/(?<=\p{Ll}|\p{Nd})(\p{Lu})/u', ' $1', $value) ?? $value;
    $value = preg_replace('/(?<=\p{Lu})(\p{Lu})(?=\p{Ll})/u', ' $1', $value) ?? $value;
    $value = str_replace(['_', '-'], ' ', $value);

    return trim($value);
};

$resolveCategory = static function (string $shortName): string {
    $normalized = strtolower($shortName);

    foreach (['woo', 'product', 'cart', 'checkout', 'shop', 'mini-cart'] as $needle) {
        if (str_contains($normalized, $needle)) {
            return 'ecommerce';
        }
    }

    foreach (['form', 'login', 'register', 'forgot', 'search'] as $needle) {
        if (str_contains($normalized, $needle)) {
            return 'forms';
        }
    }

    foreach (['facebook', 'instagram', 'twitter', 'social'] as $needle) {
        if (str_contains($normalized, $needle)) {
            return 'social';
        }
    }

    foreach (['menu', 'header', 'section', 'column', 'columns', 'grid', 'layout', 'container', 'wrapper'] as $needle) {
        if (str_contains($normalized, $needle)) {
            return 'layout';
        }
    }

    foreach (['post', 'author', 'comments', 'pagination', 'dynamic', 'term', 'adjacent', 'related', 'upsell', 'facet'] as $needle) {
        if (str_contains($normalized, $needle)) {
            return 'dynamic';
        }
    }

    foreach (['image', 'gallery', 'video', 'slider', 'map', 'lottie', 'icon'] as $needle) {
        if (str_contains($normalized, $needle)) {
            return 'media';
        }
    }

    return 'reference';
};

$referenceBlocks = [];

